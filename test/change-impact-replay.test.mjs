import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {FilePlanningMemoryStore} from '../dist/src/planning/memory-store.js';
import {buildChangeImpactTable} from '../dist/src/planning/change-impact.js';
import {buildUserReviewTable} from '../dist/src/planning/user-review.js';
import {exportUserReviewBundle} from '../dist/src/planning/review-export.js';
import {sessionFileHashes,planningSessionStatus} from '../dist/src/planning/session.js';

test('actual parking revision maps changed evidence without clearing blockers or mutating snapshots',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'impact-replay-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const archive='docs/acceptance/parking-v2-20261110/parking-export-c7572906.tar.gz';
 assert.equal(createHash('sha256').update(await readFile(archive)).digest('hex'),'a7d7aea9d3fac4b70f7b9a1265465b3bbe31ca09e9c21082512dacc1921c6385');
 assert.equal(spawnSync('tar',['-xzf',archive,'-C',dir],{encoding:'utf8'}).status,0);
 const root=join(dir,'parking-export-c7572906'),before=await sessionFileHashes(root),memory=new FilePlanningMemoryStore(join(root,'session/memory'));
 const id='parking-planning-trial',pid=id+'-plan';
 const scope=await memory.getScopeContract(id,1),previousPlan=await memory.getPlanDraft(id,pid,1),plan=await memory.getPlanDraft(id,pid,2);
 const previousReview=await memory.getPlanReview(id,pid,1),review=await memory.getPlanReview(id,pid,2),planning=await memory.getPlanningLoopState(id);
 const input={scope,plan,previousPlan,previousScope:scope,previousReview,review};
 const impact=buildChangeImpactTable(input);
 assert.equal(impact.mode,'same_scope');assert.ok(impact.changes.length);assert.ok(impact.unmappedChanges.length);
 assert.deepEqual(new Set(impact.rows.map(r=>r.category)),new Set(['requirement','constraint','acceptance','storage_rule']));
 assert.ok(impact.rows.some(r=>r.label.startsWith('updatedAt:')&&r.status==='candidate'));
 assert.ok(impact.rows.find(r=>r.label.startsWith('createdAt:')).localWarning);
 assert.ok(impact.blockers.some(r=>r.id==='issue-storage-validation-6'));
 assert.equal(impact.effectsOnPolicy,'none');assert.equal(impact.implementationVerification,'not_performed');
 const table=buildUserReviewTable({...input,planning,includeChangeImpact:true});
 assert.ok(table.changeImpact);await exportUserReviewBundle(join(dir,'view'),plan,table);
 const bundle=JSON.parse(await readFile(join(dir,'view/bundle.json'),'utf8'));
 for(const file of ['change-impact.md','change-impact.json'])assert.equal(createHash('sha256').update(await readFile(join(dir,'view',file))).digest('hex'),bundle.hashes[file]);
 const forged=structuredClone(review);forged.revisionAudit.baseline.content+='\nforged baseline';
 forged.revisionAudit.baseline.contentSha256=createHash('sha256').update(forged.revisionAudit.baseline.content).digest('hex');
 assert.throws(()=>buildChangeImpactTable({...input,review:forged}),/수정 검토의 기준 원문/);
 assert.equal(planning.status,'awaiting_user_input');assert.equal((await planningSessionStatus(join(root,'session'))).budget.usedCalls,7);
 assert.deepEqual(await sessionFileHashes(root),before);
});
